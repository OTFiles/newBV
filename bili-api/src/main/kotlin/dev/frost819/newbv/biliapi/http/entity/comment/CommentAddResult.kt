package dev.frost819.newbv.biliapi.http.entity.comment

/**
 * 发表评论的结果。
 *
 * 保留原始 `code` 而不是复用 [dev.frost819.newbv.biliapi.http.entity.BiliResponse.getResponseData]
 * 的「非 0 一律抛异常」策略，原因有二：
 * 1. 发表评论的失败原因对用户是可操作的——「评论区已关闭」应当直接放弃，
 *    「需要评论验证码」应当引导去 App 验证，「重复评论」应当提示不要刷屏。
 *    统一抛一个异常只能显示同一句话，用户无法判断该做什么。
 * 2. 部分错误码（如 12035 被 UP 主拉黑）需要给出比服务端 message 更明确的解释。
 *
 * 错误码含义参考社区文档 `docs/comment/action.md`（bilibili-API-collect）。
 *
 * @property code B 站业务返回码，0 表示成功
 * @property message 服务端返回的原始提示
 * @property rpid 新评论 ID，成功但服务端未返回时为 0
 */
data class CommentAddResult(
    val code: Int,
    val message: String,
    val rpid: Long,
) {
    /** 是否发表成功。 */
    val isSuccess: Boolean get() = code == 0

    /**
     * 面向用户的失败提示。
     *
     * 已知错误码给出可操作的中文说明；未知错误码回退到服务端 message
     * （通常是「操作太快啦」这类本就可读的文案），再兜底为带 code 的通用提示，
     * 保证任何情况下都不会弹出一个空字符串。
     */
    val userMessage: String
        get() =
            when (code) {
                0 -> ""
                // --- 鉴权与频率 ---
                -101 -> "请先登录后再发表评论"
                -102 -> "该账号已被封停，无法发表评论"
                -111 -> "登录校验已失效，请重新登录"
                -509 -> "发送太快了，请稍后再试"
                // --- 评论区状态 ---
                12002, 12052 -> "该视频的评论区已关闭"
                12003 -> "该视频已禁止回复"
                12009 -> "评论区类型不受支持"
                12045 -> "该视频需要购买后才能发表评论"
                // --- 内容问题 ---
                12015 -> "需要完成验证码校验，请到 B 站官方 App 发送一次评论后再试"
                12016 -> "评论内容包含敏感信息"
                12025 -> "评论字数过多"
                12051 -> "请勿重复发表相同内容"
                // --- 关系问题 ---
                12035 -> "你已被该 UP 主加入评论黑名单"
                // --- 目标不存在 ---
                12006, -404 -> "该评论已不存在，可能已被删除"
                12001 -> "该评论区已存在相同主题"
                // --- 通用请求错误 ---
                -400 -> "请求参数有误，请稍后再试"
                else -> message.ifBlank { "发表失败（错误码 $code）" }
            }
}
